"""
Reaching Definitions Analysis.

Milestone 2 of Code Guardian AI Data Flow Analysis.

This module builds a standard forward reaching-definitions analysis
on top of the existing:

    AST → DataFlowResult
    CFG → ControlFlowGraph

For every CFG node we calculate:

    IN[n]  = definitions reaching the node
    OUT[n] = definitions reaching after the node

The analysis is intentionally isolated.

It does NOT yet:
- modify CFG
- modify ProjectAnalyzer
- modify API schemas
- modify frontend
- perform interprocedural analysis
- generate patches
"""


from __future__ import annotations

from dataclasses import dataclass, field

from backend.analysis.cfg import ControlFlowGraph
from backend.analysis.data_flow import (
    DataFlowResult,
    Definition,
)


@dataclass(frozen=True)
class DefinitionRef:
    """
    Stable identifier for one variable definition.

    Example:

        D0 → x defined at line 2
        D1 → x defined at line 5
    """

    id: str
    definition: VariableDefinition

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "name": self.definition.name,
            "line": self.definition.line,
            "kind": self.definition.kind,
            "cfg_node_ids": list(self.definition.cfg_node_ids),
        }


@dataclass
class ReachingDefinitionsResult:
    """
    Result of reaching-definitions analysis.

    IN:
        Definitions reaching the beginning of each CFG node.

    OUT:
        Definitions reaching the end of each CFG node.

    GEN:
        Definitions generated by the node.

    KILL:
        Previous definitions invalidated by the node.
    """

    function_name: str

    definitions: list[DefinitionRef] = field(default_factory=list)

    gen: dict[int, set[str]] = field(default_factory=dict)

    kill: dict[int, set[str]] = field(default_factory=dict)

    in_sets: dict[int, set[str]] = field(default_factory=dict)

    out_sets: dict[int, set[str]] = field(default_factory=dict)
    
    predecessors: dict[int, list[int]] = field(
        default_factory=dict
    )

    def to_dict(self) -> dict:
        return {
            "function": self.function_name,
            "definitions": [
                definition.to_dict()
                for definition in self.definitions
            ],
            "gen": {
                str(node_id): sorted(definition_ids)
                for node_id, definition_ids in self.gen.items()
            },
            "kill": {
                str(node_id): sorted(definition_ids)
                for node_id, definition_ids in self.kill.items()
            },
            "in": {
                str(node_id): sorted(definition_ids)
                for node_id, definition_ids in self.in_sets.items()
            },
            "out": {
                str(node_id): sorted(definition_ids)
                for node_id, definition_ids in self.out_sets.items()
            },
        }

    def get_reaching_definitions(
        self,
        node_id: int,
    ) -> list[DefinitionRef]:
        """
        Return definitions reaching the beginning of a CFG node.
        """

        reaching_ids = self.in_sets.get(node_id, set())

        definitions_by_id = {
            definition.id: definition
            for definition in self.definitions
        }

        return [
            definitions_by_id[definition_id]
            for definition_id in sorted(reaching_ids)
            if definition_id in definitions_by_id
        ]

    def get_definitions_after_node(
        self,
        node_id: int,
    ) -> list[DefinitionRef]:
        """
        Return definitions reaching the end of a CFG node.
        """

        reaching_ids = self.out_sets.get(node_id, set())

        definitions_by_id = {
            definition.id: definition
            for definition in self.definitions
        }

        return [
            definitions_by_id[definition_id]
            for definition_id in sorted(reaching_ids)
            if definition_id in definitions_by_id
        ]


class ReachingDefinitionsAnalyzer:
    """
    Performs forward reaching-definitions analysis.

    Input:

        ControlFlowGraph
                +
        DataFlowResult

    Output:

        ReachingDefinitionsResult
    """

    def analyze(
        self,
        cfg: ControlFlowGraph,
        data_flow: DataFlowResult,
    ) -> ReachingDefinitionsResult:
        """
        Run reaching-definitions analysis.

        The algorithm is:

            IN[n] = union(OUT[p]) for every predecessor p

            OUT[n] = GEN[n] union (IN[n] - KILL[n])

        Iteration continues until no IN/OUT set changes.
        """

        definitions = self._create_definition_refs(
            data_flow.definitions
        )

        result = ReachingDefinitionsResult(
            function_name=cfg.function_name,
            definitions=definitions,
            predecessors={
                node.id: cfg.get_predecessors(node.id)
                for node in cfg.get_nodes()
            },
        )

        definition_by_id = {
            definition.id: definition
            for definition in definitions
        }

        
        # Build GEN/KILL
        

        for node in cfg.get_nodes():
            node_definitions = self._definitions_for_node(
                node.id,
                definitions,
            )

            generated_ids = {
                definition.id
                for definition in node_definitions
            }

            killed_ids: set[str] = set()

            generated_names = {
                definition.definition.name
                for definition in node_definitions
            }

            for definition in definitions:
                if (
                    definition.definition.name in generated_names
                    and definition.id not in generated_ids
                ):
                    killed_ids.add(definition.id)

            result.gen[node.id] = generated_ids
            result.kill[node.id] = killed_ids

            result.in_sets[node.id] = set()
            result.out_sets[node.id] = set()

        
        # Fixed-point iteration
        

        changed = True

        while changed:
            changed = False

            for node in cfg.get_nodes():
                node_id = node.id

                predecessors = cfg.get_predecessors(node_id)

                #--------------------------------------------------
                # IN[n]
                #--------------------------------------------------

                new_in: set[str] = set()

                for predecessor_id in predecessors:
                    new_in.update(
                        result.out_sets.get(
                            predecessor_id,
                            set(),
                        )
                    )

                #--------------------------------------------------
                # OUT[n]
                #--------------------------------------------------

                new_out = (
                    result.gen[node_id]
                    |
                    (
                        new_in
                        -
                        result.kill[node_id]
                    )
                )

                if new_in != result.in_sets[node_id]:
                    result.in_sets[node_id] = new_in
                    changed = True

                if new_out != result.out_sets[node_id]:
                    result.out_sets[node_id] = new_out
                    changed = True

        return result

   
    # Definition IDs
   

    @staticmethod
    def _create_definition_refs(
        definitions: list[Definition],
    ) -> list[DefinitionRef]:
        """
        Assign stable IDs to definitions.

        Definition order is preserved.

        Example:

            x = 10       → D0
            y = x        → D1
            x = 20       → D2
        """

        return [
            DefinitionRef(
                id=f"D{index}",
                definition=definition,
            )
            for index, definition in enumerate(definitions)
        ]

   
    # CFG mapping
   

    @staticmethod
    def _definitions_for_node(
        node_id: int,
        definitions: list[DefinitionRef],
    ) -> list[DefinitionRef]:
        """
        Find definitions generated by a CFG node.

        DataFlowAnalyzer already stores CFG node IDs inside each
        VariableDefinition.
        """

        return [
            definition
            for definition in definitions
            if node_id in definition.definition.cfg_node_ids
        ]